    fn test_build_pipeline_error_creates_failure_report() {
        use super::super::rsu::{Rsu, RsuMeta, RsuSteeringPolicy, RsuExecution, ThinkingBudget, RsuPhases};

        let coordinator = PipelineCoordinator::new();

        let rsu = Rsu {
            context: "https://kiro.ai".to_string(),
            rsu_type: "SegmentTask".to_string(),
            id: "segment_002".to_string(),
            meta: RsuMeta {
                parent_goal: "Analyze thermal anomaly".to_string(),
                thinking_budget: ThinkingBudget::Medium,
                steering_ref: "steering/test.md".to_string(),
                steering_policy: RsuSteeringPolicy::precision(),
                context_ttl_seconds: 30,
                created_at: Utc::now(),
            },
            phases: RsuPhases {
                observation: "Observe".to_string(),
                reasoning: "Reason".to_string(),
                accuracy_check: "Check".to_string(),
            },
            execution: RsuExecution {
                action: "queryNautivecs".to_string(),
                parameters: serde_json::json!({}),
            },
            dependencies: vec![],
        };

        let completed = vec![PipelineSegmentOutput {
            rsu_id: "segment_001".to_string(),
            phases: vec![PhaseOutput {
                phase: Phase::Observation,
                content: "Done.".to_string(),
                tokens_used: 50,
                elapsed_ms: 100,
            }],
            drift_score: 0.01,
            retries: 0,
            status: SegmentStatus::Completed,
        }];

        let error = coordinator.build_pipeline_error(
            "segment_002",
            1,
            "LLM timeout after retry",
            2,
            "Analyze thermal anomaly",
            &[rsu],
            &completed,
        );

        // Verify the error can be downcast to PipelineError
        let pipeline_error = error.downcast_ref::<PipelineError>().unwrap();
        assert_eq!(pipeline_error.report.failed_rsu_id, "segment_002");
        assert_eq!(pipeline_error.report.failed_segment_index, 1);
        assert_eq!(pipeline_error.report.error_message, "LLM timeout after retry");
        assert_eq!(pipeline_error.report.retries_attempted, 2);

        // Requirement 12.3: Pipeline state preserves completed outputs for resume
        let state = &pipeline_error.report.pipeline_state;
        assert_eq!(state.objective, "Analyze thermal anomaly");
        assert_eq!(state.completed_outputs.len(), 1);
        assert_eq!(state.completed_outputs[0].rsu_id, "segment_001");
        assert_eq!(state.failed_segment_index, 1);
        assert_eq!(state.retry_count, 2);
    }

