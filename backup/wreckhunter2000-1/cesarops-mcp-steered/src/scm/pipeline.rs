//! Pipeline Coordinator — phase execution, retry logic, and pipeline orchestration.
//!
//! The PipelineCoordinator manages the full segment chain:
//! - Sequencing RSUs from the Segmenter
//! - Enforcing strict phase ordering (observation → reasoning → accuracy_check)
//! - Calling Input/Output guardrails around each segment
//! - Cross-segment validation between segments
//! - Retry logic with max 3 retries before pipeline failure
//! - Error handling with resume capability
//! - Context TTL eviction for low-VRAM hardware
//!
//! Requirements covered: 8.1, 8.2, 8.3, 8.4, 8.5, 6.1, 6.2, 6.3, 6.4, 12.1, 12.2, 12.3, 12.4, 12.5

